export type FlowStep = {
  /** 고유 id — 테스트와 다이어그램이 이 값으로 합친다 */
  id: string;
  /** 화면에 보이는 이름 — "0단 라우팅"처럼 단계 번호를 포함한다 */
  이름: string;
  행위자: FlowActor;
  /** 한 줄: 이 단계가 무엇을 하는가 */
  하는일: string;
  /** 한 줄: 이 단계가 실패하면 무엇을 보는가 */
  실패하면: string;
  /** 클릭하면 실제로 그 화면·탭으로 이동 — 장식이 아니라 내비게이션 */
  보는곳: { view: FlowView; tab?: FlowTab; 라벨: string };
};

