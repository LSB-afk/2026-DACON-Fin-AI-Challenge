/**
 * 세 국적 명단은 서로 겹치지 않는다 — 온톨로지 공리의 강제 지점.
 *
 * 연금납부여부는 협정면제 → 적용제외 → 확인 순서로 훑는다. 두 명단이 한 나라를
 * 함께 갖고 있으면 앞의 분기가 조용히 이기고, 뒤 명단이 말해야 할 판정은 아무도 못 본다.
 * 이 검사가 없던 때의 사고: 2차 출처를 믿고 베트남을 적용제외국에 넣을 뻔했다.
 * 공단 원본 PDF가 그 서술을 뒤집었고, 그대로 나갔으면 한 사람당 700만 원짜리
 * 오답이었다 (02_제품/02_S2_출국정산.md 3절).
 *
 * 반환: 겹친 나라와 명단 쌍. 빈 배열이면 통과다. departure.test.ts 와
 * scripts/verify-golden.mjs 가 매 실행마다 부른다 — 손으로 명단을 고치다
 * 겹치게 하면 CI 가 멈춘다.
 */
export function 연금명단_교차검사(): string[] {
  const 명단들 = [
    ["사업장 적용제외국", 국민연금_사업장_적용제외국],
    ["협정면제(E-9)", 국민연금_협정면제_E9],
    ["납부 확인국", 국민연금_납부_확인국],
  ] as const;
  const 교차: string[] = [];
  for (let i = 0; i < 명단들.length; i++) {
    for (let j = i + 1; j < 명단들.length; j++) {
      for (const 나라 of 명단들[i][1]) {
        if ((명단들[j][1] as readonly string[]).includes(나라))
          교차.push(`${나라} (${명단들[i][0]} ∩ ${명단들[j][0]})`);
      }
    }
  }
  return 교차;
}

